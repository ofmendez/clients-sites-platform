function createPagination() {

  pagination.innerHTML = songsData
    .map((song, index) => `
      <button
        class="songs-pagination__item"
        type="button"
        data-index="${index}"
        aria-label="Ver ${song.title}"
      ></button>
    `)
    .join("");

  pagination
    .querySelectorAll(".songs-pagination__item")
    .forEach(button => {

      button.addEventListener("click", () => {

        const index = Number(button.dataset.index);

        goTo(index);

      });

    });

}


/* =========================================================
   CREAR TARJETA
   ========================================================= */

function cardMarkup(song, logicalIndex, offset) {

  const feat = song.feat
    ? `
      <div class="song-card__feat">
        Ft. ${song.feat}
      </div>
    `
    : `
      <div class="song-card__feat song-card__feat--empty">
        &nbsp;
      </div>
    `;

  const links = Object.entries(platformIcons)
    .map(([key, icon]) => {

      const href = song.links[key];
      const disabled = !href;

      return `
        <a
          class="song-platform${disabled ? " is-disabled" : ""}"
          href="${href || "#"}"
          ${
            disabled
              ? 'aria-disabled="true" tabindex="-1"'
              : 'target="_blank" rel="noopener noreferrer"'
          }
          aria-label="${platformNames[key]}"
        >
          <img
            src="${icon}"
            alt=""
          >
        </a>
      `;
    })
    .join("");

const media = offset === 0
  ? `
      <div class="song-card__video-wrap">

        <img
          class="song-card__video-placeholder"
          src="${song.thumb}"
          alt=""
          draggable="false"
        >

        <video
          muted
          loop
          playsinline
          webkit-playsinline
          preload="auto"
          poster="${song.thumb}"
        >
          <source
            src="${song.preview}"
            type="video/mp4"
          >
        </video>

      </div>
    `
  : `
      <img
        class="song-card__thumb"
        src="${song.thumb}"
        alt=""
        draggable="false"
      >
    `;


  return `
    <article
      class="song-card${offset === 0 ? " is-active" : ""}"
      data-index="${logicalIndex}"
      data-offset="${offset}"
    >

      <button
        class="song-card__media"
        type="button"
        aria-label="Ver video de ${song.title}"
      >

        ${media}

        <div class="song-card__fallback">
          <span>
            ${String(logicalIndex + 1).padStart(2, "0")}
          </span>
        </div>

      </button>

      <button
        class="song-card__title"
        type="button"
      >
        ${song.title}
      </button>

      ${feat}

      <nav
        class="song-card__platforms"
        aria-label="Escuchar ${song.title}"
      >
        ${links}
      </nav>

    </article>
  `;
}


/* =========================================================
   RENDERIZAR SLIDER
   ========================================================= */

function renderSongs() {

  const radius = window.innerWidth <= 800 ? 2 : 3;

  let markup = "";

  for (let offset = -radius; offset <= radius; offset++) {

    const index = wrap(activeIndex + offset);

    markup += cardMarkup(
      songsData[index],
      index,
      offset
    );
  }

  track.innerHTML = markup;

  counter.textContent = String(activeIndex + 1).padStart(2, "0");

  pagination
  .querySelectorAll(".songs-pagination__item")
  .forEach((item, index) => {

    item.classList.toggle(
      "is-active",
      index === activeIndex
    );

  });


  /* -----------------------------------------
     CONFIGURAR CADA VIDEO
     ----------------------------------------- */

  track.querySelectorAll(".song-card").forEach(card => {

    const index = Number(card.dataset.index);
    const offset = Number(card.dataset.offset);



    const video = card.querySelector("video");

if (video) {

  video.muted = true;


  /*
   * Solo enseñamos el video cuando Safari confirma
   * que realmente está reproduciéndose.
   */
  video.addEventListener("playing", () => {

    video.classList.add("is-playing");

  });


  /*
   * Si el video vuelve a quedar detenido antes
   * de empezar, seguimos mostrando el thumbnail.
   */
  video.addEventListener("error", () => {

    video.classList.remove("is-playing");

    card.classList.add("has-no-preview");

  }, { once: true });


  const playPromise = video.play();


  if (playPromise) {

    playPromise.catch(() => {

      /*
       * iPhone puede bloquear autoplay, especialmente
       * en determinadas condiciones de energía.
       *
       * No mostramos el video negro:
       * queda visible el thumbnail que está debajo.
       */
      video.classList.remove("is-playing");

      card.classList.add("is-autoplay-blocked");

    });

  }

}


    /* -----------------------------------------
       CLICK EN VIDEO
       ----------------------------------------- */

    card
      .querySelector(".song-card__media")
      .addEventListener("click", () => {

        if (suppressClick) return;

        if (offset === 0) {
  openVideo(index);
} else {
  goTo(index);
}
      });


    /* -----------------------------------------
       CLICK EN NOMBRE
       ----------------------------------------- */

    card
      .querySelector(".song-card__title")
      .addEventListener("click", () => {

        if (suppressClick) return;

       if (offset === 0) {
  openVideo(index);
} else {
  goTo(index);
}

      });

  });
}


function getSlideDistance() {
  const card = track.querySelector(".song-card");

  if (!card) return 0;

  const cardWidth = card.offsetWidth;

  const styles = getComputedStyle(track);
  const gap = parseFloat(styles.columnGap || styles.gap) || 0;

  return cardWidth + gap;
}


/* =========================================================
   NAVEGACIÓN
   ========================================================= */

function animateSlide(step) {

  if (isAnimating) return;

  const currentCard =
    track.querySelector(".song-card.is-active");

  const targetCard =
    track.querySelector(
      `.song-card[data-offset="${step}"]`
    );

  if (!currentCard || !targetCard) return;

  isAnimating = true;


  /*
   * DISTANCIA REAL ENTRE LAS DOS TARJETAS
   */
  const currentRect =
    currentCard.getBoundingClientRect();

  const targetRect =
    targetCard.getBoundingClientRect();

  const currentCenter =
    currentRect.left + currentRect.width / 2;

  const targetCenter =
    targetRect.left + targetRect.width / 2;

  const slideDistance =
    targetCenter - currentCenter;


  /*
   * Cambiamos visualmente cuál será la activa.
   */
  currentCard.classList.remove("is-active");
  targetCard.classList.add("is-active");


  /*
   * Movemos exactamente la distancia necesaria
   * para llevar el target al centro.
   */
  track.style.transition =
    `transform ${SLIDE_DURATION}ms cubic-bezier(.22,.61,.36,1)`;

  track.style.transform =
    `translateX(calc(-50% - ${slideDistance}px))`;


  setTimeout(() => {

    track.style.transition = "none";

    activeIndex =
      wrap(activeIndex + step);

    renderSongs();

    track.style.transform =
      "translateX(-50%)";

    requestAnimationFrame(() => {

      track.style.transition = "";

      isAnimating = false;

    });

  }, SLIDE_DURATION);

}


function go(step) {

  if (isAnimating) return;

  animateSlide(step, false);

}


function animateToIndex(index) {

  if (isAnimating) return;

  index = wrap(index);

  if (index === activeIndex) return;


  let difference =
    index - activeIndex;


  if (difference > songsData.length / 2) {
    difference -= songsData.length;
  }

  if (difference < -songsData.length / 2) {
    difference += songsData.length;
  }


  /*
   * Si la tarjeta está dentro del DOM actual,
   * podemos movernos directamente hasta ella.
   */
  const targetCard =
    track.querySelector(
      `.song-card[data-index="${index}"]`
    );


  if (targetCard) {

    const offset =
      Number(targetCard.dataset.offset);

    animateSlide(offset);

    return;

  }


  /*
   * Si está fuera del grupo renderizado,
   * hacemos el cambio directo.
   *
   * Esto aplica principalmente a la paginación.
   */
  activeIndex = index;

  renderSongs();

}

function goTo(index) {

  index = wrap(index);

  if (
    index === activeIndex ||
    isAnimating
  ) {
    return;
  }

  animateToIndex(index);

}


/* =========================================================
   MODAL DE YOUTUBE
   ========================================================= */

function openVideo(index) {

  const song = songsData[index];

  modal.classList.add("is-open");

  modal.setAttribute(
    "aria-hidden",
    "false"
  );

  document.body.classList.add("modal-open");


  if (song.youtubeId) {

    modalFrame.src =
      `https://www.youtube.com/embed/${song.youtubeId}?autoplay=1&rel=0`;

    modalFrame.hidden = false;

    modalEmpty.hidden = true;

  } else {

    modalFrame.src = "";

    modalFrame.hidden = true;

    modalEmpty.hidden = false;

  }


  modalClose.focus();

}


function closeVideo() {

  modal.classList.remove("is-open");

  modal.setAttribute(
    "aria-hidden",
    "true"
  );

  modalFrame.src = "";

  document.body.classList.remove("modal-open");

}


