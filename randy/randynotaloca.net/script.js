/* =========================================================
   DRAG / SWIPE
   ========================================================= */

viewport.addEventListener(
  "pointerdown",
  event => {

    // Solo botón izquierdo del mouse
    if (
      event.pointerType === "mouse" &&
      event.button !== 0
    ) {
      return;
    }

    dragging = true;

    suppressClick = false;

    dragStart = event.clientX;

    dragDelta = 0;

    /*
     * IMPORTANTE:
     * todavía NO hacemos setPointerCapture().
     *
     * Así un click normal puede llegar correctamente
     * al botón del video o al título.
     */
  }
);


viewport.addEventListener("pointermove", event => {

  if (!dragging || isAnimating) return;

  dragDelta =
    event.clientX - dragStart;

  if (Math.abs(dragDelta) > 8) {

  if (!suppressClick) {

    suppressClick = true;

    /*
     * Solo capturamos el pointer cuando YA sabemos
     * que el usuario realmente está arrastrando.
     */
    try {
      viewport.setPointerCapture(event.pointerId);
    } catch (error) {
      // Algunos navegadores pueden haber perdido el pointer.
    }

    viewport.classList.add("is-dragging");
  }

}

  const direction =
    dragDelta < 0 ? 1 : -1;

  const currentCard =
    track.querySelector(".song-card.is-active");

  const targetCard =
    track.querySelector(
      `.song-card[data-offset="${direction}"]`
    );

  /*
   * Movimiento horizontal siguiendo el dedo.
   */
  track.style.transition = "none";

  track.style.transform =
  `translateX(calc(-50% + ${dragDelta}px))`;


  /*
   * Progreso 0 → 1.
   *
   * A unos 180px consideramos que el cambio
   * visual está completo.
   */
  const progress =
    Math.min(
      Math.abs(dragDelta) / 180,
      1
    );


  if (currentCard && targetCard) {

    const mobile =
      window.innerWidth <= 800;

    const sideScale =
      mobile ? 0.71 : 0.72;


    /*
     * ACTUAL:
     * 1 → .71/.72
     */
    const currentScale =
      1 - ((1 - sideScale) * progress);


    /*
     * ENTRANTE:
     * .71/.72 → 1
     */
    const targetScale =
      sideScale + ((1 - sideScale) * progress);


    currentCard.style.transition = "none";
    targetCard.style.transition = "none";

    currentCard.style.transform =
      `scale(${currentScale})`;

    targetCard.style.transform =
      `scale(${targetScale})`;


    currentCard.style.opacity =
      1 - (.55 * progress);

    targetCard.style.opacity =
      .45 + (.55 * progress);

  }

});


function endDrag(event) {

  if (!dragging) return;

  dragging = false;

  viewport.classList.remove("is-dragging");

  try {
  if (viewport.hasPointerCapture(event?.pointerId)) {
    viewport.releasePointerCapture(event.pointerId);
  }
} catch (error) {}

/*
 * Si nunca superamos el umbral de movimiento,
 * esto fue un CLICK, no un drag.
 *
 * No tocamos transform ni transition porque
 * inmediatamente después se disparará el click
 * normal de la tarjeta.
 */
if (!suppressClick) {
  dragDelta = 0;
  return;
}

  const delta = dragDelta;

  const direction =
    delta < 0 ? 1 : -1;

  const currentCard =
    track.querySelector(".song-card.is-active");

  const targetCard =
    track.querySelector(
      `.song-card[data-offset="${direction}"]`
    );

  const shouldChange =
    Math.abs(delta) > 55;


  /*
   * =========================================
   * NO CAMBIA DE CANCIÓN
   * =========================================
   */

  if (!shouldChange) {

    track.style.transition =
      "transform 300ms cubic-bezier(.22,.61,.36,1)";

    track.style.transform =
      "translateX(-50%)";


    if (currentCard) {

      currentCard.style.transition =
        "transform 300ms cubic-bezier(.22,.61,.36,1), opacity 300ms ease";

      currentCard.style.transform = "";
      currentCard.style.opacity = "";

    }


    if (targetCard) {

      targetCard.style.transition =
        "transform 300ms cubic-bezier(.22,.61,.36,1), opacity 300ms ease";

      targetCard.style.transform = "";
      targetCard.style.opacity = "";

    }


    setTimeout(() => {

      track.style.transition = "";
      track.style.transform = "";

      if (currentCard) {
        currentCard.style.transition = "";
        currentCard.style.transform = "";
        currentCard.style.opacity = "";
      }

      if (targetCard) {
        targetCard.style.transition = "";
        targetCard.style.transform = "";
        targetCard.style.opacity = "";
      }

    }, 300);

  }


  /*
   * =========================================
   * SÍ CAMBIA DE CANCIÓN
   * =========================================
   */

 else {

  isAnimating = true;

  const slideDistance = getSlideDistance();

  /*
   * Posición que ya alcanzó el track durante el drag.
   */
  const currentDragPosition = delta * 0.75;

  /*
   * Posición FINAL exacta.
   *
   * direction 1  = siguiente = izquierda
   * direction -1 = anterior  = derecha
   */
  const finalPosition =
    -slideDistance * direction;


  /*
   * Convertimos las tarjetas a sus estados finales.
   */
  currentCard.style.transition =
    `transform ${SLIDE_DURATION}ms cubic-bezier(.22,.61,.36,1),
     opacity ${SLIDE_DURATION}ms ease`;

  targetCard.style.transition =
    `transform ${SLIDE_DURATION}ms cubic-bezier(.22,.61,.36,1),
     opacity ${SLIDE_DURATION}ms ease`;


  currentCard.classList.remove("is-active");
  targetCard.classList.add("is-active");


  /*
   * Quitamos los valores interpolados del drag.
   * CSS continúa hacia el estado final.
   */
  currentCard.style.transform = "";
  currentCard.style.opacity = "";

  targetCard.style.transform = "";
  targetCard.style.opacity = "";


  /*
   * El track está actualmente en:
   *
   * -50% + currentDragPosition
   *
   * y continúa directamente desde ahí hasta:
   *
   * -50% + finalPosition
   *
   * SIN volver primero al centro.
   */
  track.style.transition =
    `transform ${SLIDE_DURATION}ms cubic-bezier(.22,.61,.36,1)`;

  track.style.transform =
    `translateX(calc(-50% + ${finalPosition}px))`;


  setTimeout(() => {

    track.style.transition = "none";

    activeIndex =
      wrap(activeIndex + direction);

    renderSongs();

    track.style.transform =
      "translateX(-50%)";


    requestAnimationFrame(() => {

      track.style.transition = "";

      isAnimating = false;

    });

  }, SLIDE_DURATION);

}


  dragDelta = 0;


  setTimeout(() => {
    suppressClick = false;
  }, 0);

}


